"""### Hypothesis 2 (H2) Test
- **H₀**: Mean age is equal for serious vs non-serious events (μ_age(serious) = μ_age(non-serious)).
- **H₁**: Mean age is different for serious vs non-serious events (μ_age(serious) ≠ μ_age(non-serious)).
- **Test**: Welch's t-test and Mann-Whitney U test, with Cohen's d for effect size.
"""

import numpy as np
import pandas as pd
from scipy import stats

# Prepare the data
# Serious is 1 (where OUTCOME_RECORDED is 'Yes'), Non-serious is 0 (where OUTCOME_RECORDED is 'Unknown')
df['SERIOUS_FLAG'] = np.select(
    [
        (df['OUTCOME_RECORDED'] == 'Yes'),
        (df['OUTCOME_RECORDED'] == 'Unknown')
    ],
    [1, 0],
    default=np.nan
)

# Drop missing values in age or serious flag
h2_df = df.dropna(subset=['SERIOUS_FLAG', 'AGE_YRS'])

serious_age = h2_df.loc[h2_df['SERIOUS_FLAG'] == 1, 'AGE_YRS']
non_serious_age = h2_df.loc[h2_df['SERIOUS_FLAG'] == 0, 'AGE_YRS']

print(f"Serious sample size: {len(serious_age)}")
print(f"Non-serious sample size: {len(non_serious_age)}")

if len(serious_age) >= 2 and len(non_serious_age) >= 2:
    # 1. Welch's t-test
    t_res = stats.ttest_ind(serious_age, non_serious_age, equal_var=False)

    # 2. Mann-Whitney U test (non-parametric alternative)
    mwu_res = stats.mannwhitneyu(serious_age, non_serious_age, alternative='two-sided')

    # 3. Cohen's d
    n_s = len(serious_age)
    n_ns = len(non_serious_age)
    pooled_sd = np.sqrt(
        ((n_s - 1) * serious_age.var(ddof=1) + (n_ns - 1) * non_serious_age.var(ddof=1)) /
        (n_s + n_ns - 2)
    )
    d2 = (serious_age.mean() - non_serious_age.mean()) / pooled_sd

    print(f"\nSerious Mean Age: {serious_age.mean():.4f}")
    print(f"Non-serious Mean Age: {non_serious_age.mean():.4f}")
    print(f"\nWelch's T-statistic: {t_res.statistic:.4f}")
    print(f"Welch's T-test P-value: {t_res.pvalue}")
    print(f"Mann-Whitney U statistic: {mwu_res.statistic:.4f}")
    print(f"Mann-Whitney U P-value: {mwu_res.pvalue}")
    print(f"Cohen's d: {d2:.4f}")

    if t_res.pvalue < 0.05:
        print("\nDecision: Reject H0 (There is a significant difference in age between the two groups)")
    else:
        print("\nDecision: Fail to Reject H0 (No significant age difference detected)")
else:
    print("\nCannot perform test: insufficient sample size in one or both groups.")