import numpy as np
import pandas as pd

# Create a combined serious outcome recording indicator
outcome_columns = [
    'DIED_STATUS',
    'HOSPITAL_STATUS',
    'LIFE_THREATENING_STATUS'
]

# Convert status values to lowercase for checking
status_data = df_raw[outcome_columns].fillna('').apply(
    lambda col: col.astype(str).str.strip().str.lower()
)

# If at least one serious outcome is recorded as Yes
df_raw['SERIOUS_RECORDED'] = (
    status_data == 'yes'
).any(axis=1).astype(int)

# Create readable labels
df_raw['OUTCOME_GROUP'] = df_raw['SERIOUS_RECORDED'].map({
    1: 'Serious Outcome Recorded',
    0: 'No Serious Outcome Recorded'
})

print("Outcome Distribution:")
print(df_raw['OUTCOME_GROUP'].value_counts())

print("\nOutcome Percentages:")
print(
    df_raw['OUTCOME_GROUP']
    .value_counts(normalize=True)
    .mul(100)
    .round(2)
)

print("\nTotal Records:", len(df_raw))

import numpy as np
import pandas as pd
from scipy.stats import chi2_contingency

# Identify manufacturer names
manufacturer = df_raw['COVID_MANUFACTURERS'].astype(str).str.upper()

pfizer = manufacturer.str.contains('PFIZER', na=False)
moderna = manufacturer.str.contains('MODERNA', na=False)
janssen = manufacturer.str.contains('JANSSEN', na=False)

# Count matched manufacturers
manufacturer_count = (
    pfizer.astype(int) +
    moderna.astype(int) +
    janssen.astype(int)
)

# Keep only records with exactly one known manufacturer
df_h1 = df_raw[manufacturer_count == 1].copy()

df_h1['MANUFACTURER_GROUP'] = np.select(
    [
        pfizer[manufacturer_count == 1],
        moderna[manufacturer_count == 1],
        janssen[manufacturer_count == 1]
    ],
    ['Pfizer', 'Moderna', 'Janssen'],
    default='Other'
)

# Create contingency table
contingency_table = pd.crosstab(
    df_h1['MANUFACTURER_GROUP'],
    df_h1['OUTCOME_GROUP']
)

print("Contingency Table:")
print(contingency_table)

# Chi-Square Test
chi2, p_value, dof, expected = chi2_contingency(contingency_table)

print("\nChi-Square Test Results")
print("-----------------------")
print("Chi-Square Statistic:", round(chi2, 4))
print("Degrees of Freedom:", dof)
print("P-value:", p_value)

alpha = 0.05

if p_value < alpha:
    print("Decision: Reject H0")
    print("Conclusion: There is a significant association.")
else:
    print("Decision: Fail to Reject H0")
    print("Conclusion: There is no significant evidence of an association.")

"""**H1: Association Between Vaccine Manufacturer and Serious Outcome Recording**

**Null Hypothesis (H₀):** There is no significant association between vaccine manufacturer and serious outcome recording.

**Alternative Hypothesis (H₁):** There is a significant association between vaccine manufacturer and serious outcome recording.

**Statistical Test:** Chi-Square Test of Independence

**Significance Level:** α = 0.05

**Test Results:**
- Chi-Square Statistic (χ²) = 62.3668
- Degrees of Freedom = 2
- P-value = 2.8657 × 10⁻¹⁴

**Decision:** Since the p-value is less than 0.05, the null hypothesis (H₀) is rejected.

**Conclusion:** There is a statistically significant association between vaccine manufacturer and serious outcome recording in this dataset. The distribution of recorded serious outcomes differs across the vaccine manufacturer groups.
"""

from scipy.stats import ttest_ind, mannwhitneyu

# Prepare the two groups
serious_age = df_raw.loc[
    df_raw['SERIOUS_RECORDED'] == 1, 'AGE_YRS'
]

no_serious_age = df_raw.loc[
    df_raw['SERIOUS_RECORDED'] == 0, 'AGE_YRS'
]

# Descriptive statistics
print("Group Summary")
print("------------------------")
print("Serious Outcome Recorded:")
print("Count:", len(serious_age))
print("Mean Age:", round(serious_age.mean(), 2))
print("Median Age:", round(serious_age.median(), 2))

print("\nNo Serious Outcome Recorded:")
print("Count:", len(no_serious_age))
print("Mean Age:", round(no_serious_age.mean(), 2))
print("Median Age:", round(no_serious_age.median(), 2))

# Independent T-Test (Welch's T-Test)
t_stat, t_p_value = ttest_ind(
    serious_age,
    no_serious_age,
    equal_var=False
)

# Mann-Whitney U Test
u_stat, u_p_value = mannwhitneyu(
    serious_age,
    no_serious_age,
    alternative='two-sided'
)

print("\nIndependent T-Test Results")
print("------------------------")
print("T Statistic:", round(t_stat, 4))
print("P-value:", t_p_value)

print("\nMann-Whitney U Test Results")
print("------------------------")
print("U Statistic:", u_stat)
print("P-value:", u_p_value)

alpha = 0.05

print("\nFinal Decisions")
print("------------------------")

print("Independent T-Test:")
print("Reject H0" if t_p_value < alpha else "Fail to Reject H0")

print("Mann-Whitney U Test:")
print("Reject H0" if u_p_value < alpha else "Fail to Reject H0")

